-- The upstream files a load reads, one row per file, kept apart from the log of each run.
-- Facts that do not change from run to run (where the file comes from, which table it is parsed into, whether
-- database dumps include that table's rows) belong here. load_file_log keeps what is per run.
create table load_file
(
    lf_id                bigint generated by default as identity primary key,
    lf_ld_id             bigint  not null references load (ld_id),
    lf_source            text    not null,
    lf_table_name        text,
    lf_exclude_from_dump boolean not null default false,
    unique (lf_ld_id, lf_source)
);

comment on table load_file is
    'An upstream file or query that a load reads, with the table it is parsed into. One row per file; each run is a row in load_file_log.';
comment on column load_file.lf_id is 'Surrogate key.';
comment on column load_file.lf_ld_id is 'The load that reads this file.';
comment on column load_file.lf_source is 'Where the file comes from: its URL, or the query that produces it. Unique within the load.';
comment on column load_file.lf_table_name is
    'Schema-qualified table the file is parsed into, e.g. external_resource.ncbi_danio_rerio_gene_info. Null if the load does not keep the file in a table.';
comment on column load_file.lf_exclude_from_dump is
    'True if database dumps keep the structure and comments of lf_table_name but leave out its rows, because running the load again recreates them. False (the default) dumps the rows. Read by unload_production.sh.';

-- Loads that already have log rows, under the names those rows use.
insert into load (ld_name)
select distinct l.lfl_load_name
  from load_file_log l
 where l.lfl_load_name is not null
   and not exists (select 1 from load ld where ld.ld_name = l.lfl_load_name);

update load set ld_description = 'Gene Ontology annotations for zebrafish from the EBI GOA GAF files (goa_zebrafish, goa_zebrafish_rna, goa_zebrafish_isoform).'
 where ld_name = 'GOA' and ld_description is null;
update load set ld_description = 'Function prediction annotations from the Gene Ontology (zfin-prediction.gaf).'
 where ld_name = 'FP Inferences' and ld_description is null;
update load set ld_description = 'Annotations made in the Noctua GO editor (noctua_zfin.gpad).'
 where ld_name = 'Noctua' and ld_description is null;
update load set ld_description = 'NCBI Danio rerio gene_info file, kept in external_resource.ncbi_danio_rerio_gene_info.'
 where ld_name = 'NCBI_gene_info' and ld_description is null;

-- One row per distinct file the log has seen. The test downloads from localhost are left out.
insert into load_file (lf_ld_id, lf_source, lf_table_name)
select ld.ld_id, l.lfl_source, max(l.lfl_table_name)
  from load_file_log l
  join load ld on ld.ld_name = l.lfl_load_name
 where l.lfl_source is not null
   and l.lfl_source not like 'http://localhost%'
 group by ld.ld_id, l.lfl_source;

-- The rows of this file are a mirror that the next load recreates; this is what unload_production.sh used to exclude.
update load_file set lf_exclude_from_dump = true
 where lf_table_name = 'external_resource.ncbi_danio_rerio_gene_info';

-- NCBI's list of genes not in the current annotation release is a query, not a file, and the annotation status
-- of every gene depends on its rows, so its rows are dumped.
insert into load_file (lf_ld_id, lf_source, lf_table_name, lf_exclude_from_dump)
select ld.ld_id,
       'https://eutils.ncbi.nlm.nih.gov/entrez/eutils/esearch.fcgi?db=gene&term="Danio rerio"[Organism] NOT "annotated gene"[Properties] AND alive[prop]',
       'external_resource.ncbi_not_in_current_release',
       false
  from load ld
 where ld.ld_name = 'NCBI Gene'
on conflict (lf_ld_id, lf_source) do nothing;

alter table load_file_log add column lfl_lf_id bigint references load_file (lf_id);
create index load_file_log_lf_id_idx on load_file_log (lfl_lf_id);

update load_file_log l
   set lfl_lf_id = f.lf_id
  from load_file f
  join load ld on ld.ld_id = f.lf_ld_id
 where ld.ld_name = l.lfl_load_name
   and f.lf_source = l.lfl_source;

comment on table load_file_log is
    'One row per run of a load on a file: what was downloaded and when it was processed. What stays the same between runs is in load_file.';
comment on column load_file_log.lfl_id is 'Surrogate key.';
comment on column load_file_log.lfl_lf_id is 'The file this run read (load_file). Null for rows written before load_file existed whose source could not be matched.';
comment on column load_file_log.lfl_load_name is 'Name of the load. Older copy of load_file.lf_ld_id, still written by the loads; use lfl_lf_id.';
comment on column load_file_log.lfl_filename is 'Name of the downloaded copy, often a temporary name.';
comment on column load_file_log.lfl_source is 'URL the file came from. Older copy of load_file.lf_source, still written by the loads.';
comment on column load_file_log.lfl_date is 'Date of the file: the server''s last-modified time for the GAF loads, the day of the run for NCBI gene_info.';
comment on column load_file_log.lfl_size is 'Size of the downloaded file in bytes.';
comment on column load_file_log.lfl_md5 is 'MD5 of the downloaded file, used to skip a file that has not changed.';
comment on column load_file_log.lfl_path is 'Where the downloaded copy was kept on the server that ran the load, often a temporary path.';
comment on column load_file_log.lfl_download_date is 'When the file was downloaded.';
comment on column load_file_log.lfl_release_number is 'Release the file belongs to; the GAF loads use the file date as yyyy-MM-dd.';
comment on column load_file_log.lfl_notes is 'Free text about the run.';
comment on column load_file_log.lfl_processed_date is 'When the load finished processing the file.';
comment on column load_file_log.lfl_table_name is 'Table the file was loaded into. Older copy of load_file.lf_table_name, still written by the loads.';

