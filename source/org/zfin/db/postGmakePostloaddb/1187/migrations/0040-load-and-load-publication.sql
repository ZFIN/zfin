-- A data load (NCBI Gene, GOA, ...) and the publications its records are attributed to.
-- The NCBI Gene load tells its own links apart by publication, and until now those publication
-- ids were written into loadNCBIgeneAccs.sql, prepareNCBIgeneLoad.sql and NCBIDirectPort.

create table load
(
    ld_id          bigint generated by default as identity primary key,
    ld_name        text not null unique,
    ld_description text
);

comment on table load is
    'A recurring data load, such as the NCBI Gene load. Parent of the publications its records are attributed to.';
comment on column load.ld_id is 'Surrogate key.';
comment on column load.ld_name is 'Short unique name, e.g. "NCBI Gene".';
comment on column load.ld_description is 'What the load does, for people reading the table.';

create table load_publication
(
    lp_ld_id           bigint  not null references load (ld_id),
    lp_pub_zdb_id      text    not null references publication (zdb_id),
    lp_precedence      integer,
    lp_matching_logic  text    not null,
    lp_load_managed    boolean not null default false,
    primary key (lp_ld_id, lp_pub_zdb_id),
    unique (lp_ld_id, lp_precedence)
);

comment on table load_publication is
    'Publications that records created by a load are attributed to, one row per matching method, with how the load treats them.';
comment on column load_publication.lp_ld_id is 'The load that uses this publication.';
comment on column load_publication.lp_pub_zdb_id is 'The publication that the load attributes records to.';
comment on column load_publication.lp_precedence is
    'When the load finds the same record by more than one method, the lowest number wins. Null if the load does not create new records with this publication.';
comment on column load_publication.lp_matching_logic is 'How the load matched the records it attributes to this publication, in words, e.g. "Shared RNA sequence IDs".';
comment on column load_publication.lp_load_managed is
    'True if the load deletes and replaces every record attributed only to this publication on each run (for the NCBI Gene load, the pre_delete list in prepareNCBIgeneLoad.sql). Any load that reloads its own records can use it.';

insert into load (ld_name, ld_description)
values ('NCBI Gene',
        'Matches ZFIN genes to NCBI Gene IDs and RefSeq accessions (NCBI-Gene-Load-Java job).');

-- Looked up by publication id; publications missing from a database (e.g. a test database) are skipped.
insert into load_publication (lp_ld_id, lp_pub_zdb_id, lp_precedence, lp_matching_logic, lp_load_managed)
select (select ld_id from load where ld_name = 'NCBI Gene'),
       p.zdb_id,
       v.precedence,
       v.matching_logic,
       v.load_managed
  from (values ('ZDB-PUB-020723-3', 1, 'Shared RNA sequence IDs', true),
               ('ZDB-PUB-230516-87', 2, 'Shared Ensembl IDs (2023 supplement)', true),
               ('ZDB-PUB-261014-17', 3, 'Shared Ensembl IDs from GRCz12 assemblies (2026 supplement)', true),
               ('ZDB-PUB-130725-2', 4, 'Shared Vega gene IDs (legacy matches carried forward)', false)
       ) as v (pub_zdb_id, precedence, matching_logic, load_managed)
  join publication p on p.zdb_id = v.pub_zdb_id;

